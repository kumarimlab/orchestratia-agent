#!/usr/bin/env python3
"""code.agent, adversarial review L5 (suppression variants) and M4 (unquoted secrets in evidence).

Run:  python3 tests/test_scan_code_agent_variants.py
"""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from orchestratia_agent.scanning import code_agent  # noqa: E402

results = []


def ok(n, c, d=""):
    results.append(bool(c))
    print(f"[{'PASS' if c else 'FAIL'}] {n}" + (f" — {d}" if d else ""))


def full(files):
    with tempfile.TemporaryDirectory() as d:
        for rel, text in files.items():
            os.makedirs(os.path.dirname(os.path.join(d, rel)) or d, exist_ok=True)
            with open(os.path.join(d, rel), "w") as f:
                f.write(text)
        return code_agent.run(d, None)[0]


# L5: every common suppression form is recognised, case-insensitively; file-wide forms are high
LINE = {"x = 1  # NOQA\n": "low", "x := f() //nolint\n": "low", "x = f()  # pylint: disable=no-member\n": "low",
        "x = 1  # NOSEC\n": "low", "def f(): ...  # rubocop:disable Style/Foo\n": "low", "x = 1 // NOSONAR\n": "low",
        "x = 1  # Type: Ignore\n": "low"}
FILE = {"# flake8: noqa\n": "high", "# ruff: noqa\n": "high", "// @ts-nocheck\n": "high", "# mypy: ignore-errors\n": "high",
        "# pylint: disable=all\n": "high", "/* eslint-disable */\n": "high", "# pylint: skip-file\n": "high"}
for i, (text, sev) in enumerate({**LINE, **FILE}.items()):
    fs = [f for f in full({f"m{i}.src": text}) if f["rule_id"] == "agent:suppression-no-reason"]
    ok(f"L5 {text.strip()!r} is flagged {sev}", len(fs) == 1 and fs[0]["severity"] == sev,
       [(f["severity"], f["title"]) for f in fs])
for text in ("x := f() //nolint:errcheck // closed by the caller\n", "x = f()  # pylint: disable=no-member  # C ext\n",
             "x = 1 // NOSONAR false positive, input is constant\n", "# ruff: noqa: E501 generated file\n",
             "/* eslint-disable -- generated by protoc */\n", "# mypy: ignore-errors  # vendored module\n",
             "x = 1  # NOQA: E501 long url\n"):
    fs = [f for f in full({"r.src": text}) if f["rule_id"] == "agent:suppression-no-reason"]
    ok(f"L5 with a reason, not flagged: {text.strip()!r}", not fs, [(f["severity"], f["evidence"]) for f in fs])

# M4: a code line with an unquoted secret reaches the hub only masked (PoC poc_evidence_leak, change mode)
import subprocess  # noqa: E402
SECRETS = ["Pr0d-Db!pass#2026", "s3cr3t.v4lue.k3y.9f8e7d6c5b4a39281706", "hunter2-PROD"]
GENV = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t", GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@t",
            GIT_CONFIG_GLOBAL="/dev/null", GIT_CONFIG_NOSYSTEM="1")
with tempfile.TemporaryDirectory() as d:
    g = lambda *a: subprocess.run(["git", "-C", d, *a], capture_output=True, text=True, check=True, env=GENV).stdout.strip()  # noqa: E731
    g("init", "-q")
    with open(os.path.join(d, "README"), "w") as f:
        f.write("x\n")
    g("add", "-A")
    g("commit", "-qm", "base")
    since = g("rev-parse", "HEAD")
    for rel, text in {"docker-compose.yml": f"services:\n  db:\n    environment:\n      POSTGRES_PASSWORD: {SECRETS[0]}  # TODO move\n",
                      "app.ini": f"[auth]\nsigning_key = {SECRETS[1]}  ; FIXME rotate\n",
                      ".env": f"DB_PASSWORD={SECRETS[2]} # nosec\n"}.items():
        with open(os.path.join(d, rel), "w") as f:
            f.write(text)
    fs = code_agent.run(d, since)[0]
ev = [f["evidence"] for f in fs]
ok("M4 change mode reports the three lines", len(fs) == 3, [(f["rule_id"], f["location"]["path"]) for f in fs])
ok("M4 no unquoted secret (or a 6+ char piece of one) is in any evidence",
   not [s for s in SECRETS for e in ev for k in range(len(s) - 5) if s[k:k + 6] in e], ev)

print(f"\n{sum(results)}/{len(results)} passed")
sys.exit(0 if results and all(results) else 1)
