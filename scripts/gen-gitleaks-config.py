#!/usr/bin/env python3
"""Builds orchestratia_agent/scanning/gitleaks.toml from the pinned gitleaks' own default config.

Usage:  python3 scripts/gen-gitleaks-config.py <pinned gitleaks binary> > orchestratia_agent/scanning/gitleaks.toml

The default config is embedded verbatim in the gitleaks binary, so it is read from there (the binary
is pinned by SHA-256 in manifest.json). `[extend] useDefault = true` would also inherit the default
GLOBAL allowlist, which skips files by name: *.svg, *.pdf, vendor/..., node_modules/..., lockfiles
and more — a planted secret in settings.svg was invisible. Path allowlists are repo-controlled, so
they are removed (global and per-rule; only `.git` stays). Value allowlists (placeholder values like
${VAR}, {{ x }}, true/false/null) stay: a real credential can't be made to look like a placeholder.
tests/test_scan_gitleaks_config.py re-runs this against the pinned binary and compares."""
import sys

START = b'title = "gitleaks config"'


def upstream_from_binary(path):
    """The default config as embedded in the binary: a run of printable text between NUL padding."""
    data = open(path, "rb").read()
    i = data.find(START)
    if i < 0:
        raise SystemExit("no embedded default config in that binary")
    head = data.rfind(b"# This file has been auto-generated", 0, i)
    end = i
    while end < len(data) and (0x20 <= data[end] < 0x7f or data[end] in (9, 10, 13)):
        end += 1
    return data[head:end].decode()


def transform(upstream: str) -> str:
    out = []
    lines = upstream.split("\n")
    i, in_global = 0, False
    while i < len(lines):
        ln = lines[i]
        if ln == "[allowlist]":
            in_global = True
        elif ln.startswith("[[rules]]"):
            in_global = False
        if in_global and ln == "paths = [":
            while lines[i] != "]":
                i += 1
            out += ["paths = [", "    '''(?:^|/)\\.git$''',", "]"]
            i += 1
            continue
        if in_global and ln == "    '''(?i)^true|false|null$''',":
            out.append("    '''(?i)^(?:true|false|null)$''',")     # the upstream form allows any value containing "false"
            i += 1
            continue
        if ln == "[[rules.allowlists]]":
            j = i + 1
            while j < len(lines) and lines[j] and not lines[j].startswith("["):
                j += 1
            if any(x.startswith("paths = [") for x in lines[i + 1:j]):
                i = j                                                    # drop the whole path-scoped allowlist
                while i < len(lines) and lines[i] == "":
                    i += 1
                if out and out[-1] != "":
                    out.append("")
                continue
        out.append(ln)
        i += 1
    header = ("# Pinned gitleaks configuration for code.secrets, generated by scripts/gen-gitleaks-config.py from\n"
              "# the default config embedded in the pinned gitleaks binary (manifest.json). The shim passes\n"
              "# --config=<this file>: a config inside the scanned repository is never read, and the upstream\n"
              "# path allowlists (global and per-rule) are removed — they skipped files by name (*.svg, *.pdf,\n"
              "# vendor/, node_modules/, lockfiles ...), which repository content controls. Do not edit by hand.\n")
    return header + "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(transform(upstream_from_binary(sys.argv[1])))
